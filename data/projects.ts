export const projects: Project[] = rows.map(([id, title, group, purpose, stage, access, note]) => ({
  id,
  title,
  group,
  purpose,
  stage,
  access,
  ...(note ? { note } : {}),
  ...(caseSlugs.has(id) ? { caseSlug: id } : {}),
  ...(id === "expenses" ? { searchTerms: "расходы траты затраты" } : {}),
  links: links[id] ?? [],
  ...(details[id] ? { details: details[id] } : {}),
  ...(evidence[id] ? { evidence: evidence[id] } : {}),
}));

export const featuredProjects = projects.filter((project) =>
  ["transcription", "reviews", "contracts"].includes(project.id),
);

export const caseProjects = projects.filter((project) => project.caseSlug);

export function getProject(id: string): Project | undefined {
  return projects.find((project) => project.id === id);
}
